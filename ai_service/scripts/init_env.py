"""Create ai_service/.env and wire the Django .env for local testing. Never prints secret values.

Sources (first found wins): process env -> root .env -> Scrutinize/.env (OPENAI_API_KEY only).
Existing AI_* values are kept; run with --force to regenerate ai_service/.env.

  python ai_service/scripts/init_env.py [--force]
"""

from __future__ import annotations

import re
import secrets
import sys
from pathlib import Path
from urllib.parse import urlsplit, urlunsplit

ROOT = Path(__file__).resolve().parents[2]
AI = ROOT / "ai_service"


def read_env(path: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    if path.is_file():
        for line in path.read_text(encoding="utf-8").splitlines():
            m = re.match(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$", line)
            if m and not line.lstrip().startswith("#"):
                out[m[1]] = m[2].strip().strip('"').strip("'")
    return out


def direct_pg_url(url: str) -> str:
    """Use Neon's direct endpoint (no -pooler) and a plain postgresql:// scheme."""
    parts = urlsplit(url)
    scheme = "postgresql" if parts.scheme.startswith("postgres") else parts.scheme
    netloc = parts.netloc.replace("-pooler.", ".")
    return urlunsplit((scheme, netloc, parts.path, parts.query, parts.fragment))


def mask(v: str) -> str:
    return "(set)" if v else "(missing)"


def upsert(path: Path, values: dict[str, str]) -> None:
    lines = path.read_text(encoding="utf-8").splitlines() if path.is_file() else []
    seen = set()
    for i, line in enumerate(lines):
        m = re.match(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=", line)
        if m and m[1] in values:
            lines[i] = f"{m[1]}={values[m[1]]}"
            seen.add(m[1])
    add = [f"{k}={v}" for k, v in values.items() if k not in seen]
    if add:
        if lines and lines[-1].strip():
            lines.append("")
        lines += ["# --- Antix AI service (added by ai_service/scripts/init_env.py) ---", *add]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    force = "--force" in sys.argv
    root_env = read_env(ROOT / ".env")
    scr_env = read_env(ROOT / "Scrutinize" / ".env")
    ai_env = read_env(AI / ".env")
    import os

    def pick(*names: str, sources=(os.environ, root_env)) -> str:
        for n in names:
            for src in sources:
                if src.get(n):
                    return src[n]
        return ""

    db = pick("DATABASE_URL")
    if not db:
        print("ERROR: DATABASE_URL not found (process env or root .env). The AI service shares Django's database.")
        return 1
    openai_key = pick("OPENAI_API_KEY") or scr_env.get("OPENAI_API_KEY", "")
    if openai_key.startswith("your_"):
        openai_key = ""
    base_url = pick("OPENAI_BASE_URL")  # Django's own LLM endpoint (e.g. ngrok/vLLM), optional
    django_model = pick("LLM_MODEL")

    service_key = (ai_env.get("AI_SERVICE_KEY") if not force else "") or root_env.get("AI_SERVICE_KEY") or secrets.token_urlsafe(36)
    if service_key.startswith("generate-"):
        service_key = secrets.token_urlsafe(36)

    lines = [
        "# Generated by scripts/init_env.py -- safe to edit. Gitignored.",
        f"AI_DATABASE_URL={direct_pg_url(db)}",
        f"AI_SERVICE_KEY={service_key}",
        "AI_REDIS_URL=redis://localhost:6381/2",
        "AI_ENV=dev",
        "AI_LOG_JSON=false",
        "",
    ]
    if openai_key:
        lines += [
            "# Models: OpenAI. Change AI_STRONG__MODEL to gpt-4o (or another) for higher answer quality.",
            "AI_FAST__PROVIDER=openai", "AI_FAST__MODEL=gpt-4o-mini", f"AI_FAST__API_KEY={openai_key}",
            "AI_STRONG__PROVIDER=openai", "AI_STRONG__MODEL=gpt-4o-mini", f"AI_STRONG__API_KEY={openai_key}",
            "AI_EMBED_PROVIDER=openai", "AI_EMBED_MODEL=text-embedding-3-small", "AI_EMBED_DIM=1536",
            f"AI_EMBED_API_KEY={openai_key}",
            "AI_RERANK=llm",
        ]
    else:
        lines += [
            "# No OPENAI_API_KEY found: running OFFLINE (hashing embeddings, extractive answers).",
            "# Add keys and set providers to 'openai' for real answers, then re-run migrate (embed dim is schema).",
            "AI_FAST__PROVIDER=offline", "AI_STRONG__PROVIDER=offline",
            "AI_EMBED_PROVIDER=offline", "AI_EMBED_DIM=256", "AI_RERANK=none",
        ]
    if base_url and django_model:
        lines += ["", f"# Optional: use your Django LLM endpoint ({django_model}) for the cheap 'fast' role instead:",
                  f"#AI_FAST__BASE_URL={base_url}", f"#AI_FAST__MODEL={django_model}", "#AI_FAST__DISABLE_THINKING=true"]

    target = AI / ".env"
    if target.exists() and not force:
        print(f"ai_service/.env exists -> kept (use --force to regenerate). Key {mask(ai_env.get('AI_SERVICE_KEY', ''))}")
        service_key = ai_env.get("AI_SERVICE_KEY", service_key)
    else:
        target.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print("wrote ai_service/.env")

    upsert(ROOT / ".env", {
        "AI_BACKEND": "antix",
        "AI_SERVICE_URL": "http://localhost:8100",
        "AI_SERVICE_KEY": service_key,
        "AI_FALLBACK_TO_SCRUTINIZE": "false",
    })
    print("updated root .env: AI_BACKEND=antix, AI_SERVICE_URL, AI_SERVICE_KEY")
    print(f"database: {urlsplit(direct_pg_url(db)).hostname}   openai key: {mask(openai_key)}")
    print("\nNext:  make docker-up  ->  make ai-migrate  ->  make ai-worker (terminal 2)  ->  make ai-serve (terminal 3)"
          "\n       make ai-backfill  ->  make worker (celery) + make backend  ->  open the site and use Ask AI")
    return 0


if __name__ == "__main__":
    sys.exit(main())
